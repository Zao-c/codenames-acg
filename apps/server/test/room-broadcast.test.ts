import assert from 'node:assert/strict';
import {RoomBroadcastQueue} from '../src/room-broadcast.js';
const sleep=(ms:number)=>new Promise(r=>setTimeout(r,ms));
let state=0;const seen:number[]=[];
const queue=new RoomBroadcastQueue(async()=>{seen.push(state);},1);
await Promise.all(Array.from({length:102},()=>{state++;return queue.send('burst');}));
assert.deepEqual(seen,[102],'one fresh projection covers all committed mutations');
let release!:()=>void,entered!:()=>void;
const began=new Promise<void>(r=>entered=r),gate=new Promise<void>(r=>release=r);let passes=0;
const during=new RoomBroadcastQueue(async()=>{passes++;if(passes===1){entered();await gate;}},1);
const first=during.send('room');await began;
let secondDone=false;const second=during.send('room').then(()=>secondDone=true);
release();await first;assert.equal(secondDone,false,'mid-pass mutation waits for its own fresh projection');await second;assert.equal(passes,2);
let fail=true,attempts=0;
const recovery=new RoomBroadcastQueue(async()=>{attempts++;if(fail)throw new Error('temporary publish failure');},1);
const failures=await Promise.allSettled([recovery.send('broken'),recovery.send('broken')]);assert.ok(failures.every(r=>r.status==='rejected'));assert.equal(attempts,1);
fail=false;await recovery.send('broken');assert.equal(attempts,2,'failed room can publish again without stranded promises');
const rooms:string[]=[];const isolated=new RoomBroadcastQueue(async id=>{rooms.push(id);},1);
await Promise.all([isolated.send('A'),isolated.send('B'),isolated.send('A')]);assert.deepEqual(rooms.sort(),['A','B']);
await sleep(5);console.log('Room broadcast PASS: fresh burst batching, mid-pass updates, bounded ACK wait, room isolation and failure recovery');
